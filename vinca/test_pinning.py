def test_dependencies_from_vinca_reuses_distro_and_group_packages(tmp_path):
    distro = type(
        "FakeDistro",
        (),
        {
            "name": "rolling",
            "snapshot": {},
            "additional_packages_snapshot": {},
            "prefetch_additional_package_xml": lambda self: None,
        },
    )()
    config = {
        "ros_distro": "rolling",
        "_snapshot": {},
        "_additional_packages_snapshot": {},
    }
    requirements = iter(
        [
            [{"host": ["python", "ros2-rclcpp"]}],
            [{"host": ["libboost-devel"]}],
            [{"run": ["vtk >=9"]}],
        ]
    )

    with (
        patch("vinca.distro.Distro", return_value=distro) as distro_class,
        patch("vinca.main.read_vinca_yaml", side_effect=lambda path: dict(config)),
        patch(
            "vinca.main.get_group_dependency_packages", return_value=["group-package"]
        ) as get_groups,
        patch("vinca.main.get_selected_packages", return_value=["selected"]),
        patch(
            "vinca.main.generate_dependency_requirements",
            side_effect=lambda distro, config, groups: next(requirements),
        ) as generate_requirements,
    ):
        dependencies = dependencies_from_vinca(tmp_path)

    assert dependencies == {"python", "libboost-devel", "vtk"}
    distro_class.assert_called_once()
    get_groups.assert_called_once_with(distro)
    assert generate_requirements.call_count == 3
    assert all(
        call.args[2] == ["group-package"]
        for call in generate_requirements.call_args_list
    )


def test_selects_only_migrations_done_for_all_relevant_dependencies():
    migrations = {
        "boost": BOOST_MIGRATION,
        "urdfdom": b"urdfdom:\n  - '6'\n",
        "paused": b"__migrator:\n  paused: true\nignored:\n  - 2\n",
    }
    statuses = {
        "boost": {"done": ["pcl"], "in-pr": ["vtk"]},
        "urdfdom": {"done": ["pinocchio"]},
    }

    with (
        patch(
            "vinca.pinning.get_migration_status",
            side_effect=lambda name: statuses[name],
        ),
        patch(
            "vinca.pinning.package_feedstocks",
            side_effect=lambda package: {package},
        ),
    ):
        selected, reports = select_completed_migrations(
            migrations, {"pcl", "vtk", "pinocchio"}
        )

    assert selected == ["urdfdom"]
    assert dict(reports)["boost"].startswith("waiting for vtk")
    assert "paused" not in dict(reports)


def test_migration_platform_selectors_are_respected():
    migration = b"""\
__migrator:
  kind: version
c_stdlib_version:  # [osx]
  - 12.0           # [osx]
"""

    assert _migration_applies_to_platforms(migration, ("osx-64",))
    assert not _migration_applies_to_platforms(migration, ("linux-64",))


def test_existing_active_migration_is_kept_and_overrides_are_unchanged(tmp_path):
    config_path = tmp_path / "vinca_pinning.yaml"
    config_path.write_text(
        """\
conda_forge_pinning_version: old
migrations:
  - boost
pinning_overrides:
  # This comment and value are maintained locally.
  python:
    - 3.14.* *_cp314
"""
    )
    package = (BASE_CONFIG, {"boost": BOOST_MIGRATION})
    pending_status = {"done": [], "in-pr": ["pcl"]}

    with (
        patch("vinca.pinning.download_pinning_package", return_value=package),
        patch("vinca.pinning.get_migration_status", return_value=pending_status),
        patch("vinca.pinning.package_feedstocks", side_effect=lambda name: {name}),
    ):
        version, migrations, _ = update_pinning(
            config_path,
            base_dir=tmp_path,
            dependencies={"pcl"},
            latest_distribution=("new", "https://example.invalid/package.conda"),
        )

    assert version == "new"
    assert migrations == ["boost"]
    text = config_path.read_text()
    assert "This comment and value are maintained locally." in text
    parsed = ruamel.yaml.YAML(typ="safe").load(text)
    assert parsed["pinning_overrides"] == {"python": ["3.14.* *_cp314"]}
