def test_cfep9_key_add_updates_zip_group():
    base = {
        "python": ["3.12.*", "3.13.*"],
        "is_python_min": [True, False],
        "zip_keys": [["python", "is_python_min"]],
    }
    migration = {
        "__migrator": {
            "operation": "key_add",
            "primary_key": "python",
            "ordering": {"python": ["3.12.*", "3.13.*", "3.14.*"]},
        },
        "python": ["3.14.*"],
        "is_python_min": [False],
    }

    merged = variant_add(base, migration)

    assert merged["python"] == ["3.12.*", "3.13.*", "3.14.*"]
    assert merged["is_python_min"] == [True, False, False]


def test_cfep9_merges_pin_run_as_build_and_zip_keys():
    merged = variant_add(
        {
            "pin_run_as_build": {"old": {"max_pin": "x"}},
            "zip_keys": [["python", "numpy"]],
        },
        {
            "pin_run_as_build": {"new": {"max_pin": "x.x"}},
            "zip_keys": [["python", "numpy", "is_python_min"]],
        },
    )

    assert merged["pin_run_as_build"] == {
        "old": {"max_pin": "x"},
        "new": {"max_pin": "x.x"},
    }
    assert merged["zip_keys"] == [["is_python_min", "numpy", "python"]]


def test_cfep9_scoped_migration_only_replaces_matching_platform_values():
    yaml = ruamel.yaml.YAML()
    base = yaml.load(
        """\
c_stdlib_version:
  - 2.17  # [linux]
  - 2.28  # [linux and (x86_64 or aarch64)]
  - 11.0  # [osx]
"""
    )
    migration = yaml.load(
        """\
c_stdlib_version:  # [osx]
  - 12.0           # [osx]
"""
    )

    merged = variant_add(base, migration)

    assert merged["c_stdlib_version"] == [2.17, 2.28, 12.0]
    output = io.StringIO()
    yaml.dump(merged, output)
    assert "2.17" in output.getvalue() and "# [linux]" in output.getvalue()
    assert "2.28" in output.getvalue()
    assert "12.0" in output.getvalue() and "# [osx]" in output.getvalue()


